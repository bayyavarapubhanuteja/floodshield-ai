/* colour ramps (value -> css colour) */
function lerp(a: number[], b: number[], t: number) {
  return a.map((x, i) => Math.round(x + (b[i] - x) * t));
}
function ramp(stops: [number, number[]][]) {
  return (v: number): [number, number, number, number] => {
    if (v <= stops[0][0]) return [...stops[0][1], 255] as any;
    for (let i = 1; i < stops.length; i++) {
      if (v <= stops[i][0]) {
        const t = (v - stops[i - 1][0]) / (stops[i][0] - stops[i - 1][0]);
        return [...lerp(stops[i - 1][1], stops[i][1], t), 255] as any;
      }
    }
    return [...stops[stops.length - 1][1], 255] as any;
  };
}
