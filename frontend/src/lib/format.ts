export const pretty = (s?: string | null) => (s ? s.replace(/_/g, " ").toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase()) : "—");
export const fmt = (v: any, d = 1, unit = "") => (v === null || v === undefined || Number.isNaN(v) ? "—" : `${Number(v).toFixed(d)}${unit}`);
export const pct = (v: any, d = 0) => (v === null || v === undefined ? "—" : `${(Number(v) * 100).toFixed(d)}%`);
export const depth = (m: any) => (m === null || m === undefined ? "—" : Number(m) >= 1 ? `${Number(m).toFixed(2)} m` : `${Math.round(Number(m) * 100)} cm`);
export const ttf = (m: number | null | undefined) => (m === null || m === undefined ? "Not expected" : m === 0 ? "Flooded now" : `in ${m} min`);

